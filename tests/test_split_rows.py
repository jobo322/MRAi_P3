"""Tests for split_2d_rows: compute only the sampled rows.

split_2d_rows(S, idx, Cross_Size) must be exactly equivalent to
split_2d(S, Cross_Size) restricted to `idx`, for X *and* for Norm. The
whole point of the change is that the ~524288-row matrix is never built
while the ~6400 rows that get stored stay bit-identical, so every test
here is a parity test plus one end-to-end regression against a pool that
was generated by the previous (full-matrix) implementation.

- test_parity_*        : split_2d_rows == split_2d(...)[idx], X and Norm.
- test_full_range_...  : idx = arange(H*W) == split_2d_fast.
- test_plan_pool_idx_* : plan_pool_idx() picks the same rows as build_pool().
- test_points_*        : BinSequence._points fast path == full-split path.
- test_preextract_*    : end-to-end byte-identity vs a saved pool (skipped
                         unless the local dataset and pool are present).
- test_not_slower_*    : computing ~2900 rows beats the full matrix.
"""
import json
import os
import sys
import time
import unittest

import numpy as np

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "scripts"))

from cross_extract import split_2d  # noqa: E402
from cross_extract_fast import split_2d_fast, split_2d_rows  # noqa: E402
from preextract import (build_pool, load_pair, plan_pool_idx,  # noqa: E402
                        CROSS, SHAPE)
from hard_negatives import distance_to_positive  # noqa: E402
from train_model import BinSequence  # noqa: E402  (TF is imported lazily)

DATASET_DIR = os.environ.get(
    "MRAI_DATASET",
    "/Users/abolanos/git/cheminfo/spectrum-generator/dataset")
POOL_DIR = os.environ.get(
    "MRAI_PRE_POOL", os.path.join(REPO_ROOT, "data", "pre_elong"))

SHAPES = [(256, 512), (256, 2048), (64, 65)]


def _spectrum(shape, seed=0):
    return np.random.default_rng(seed).standard_normal(shape).astype(np.float32)


def _idx_variants(h, w, seed=1):
    """Sorted, unsorted and empty index sets."""
    rng = np.random.default_rng(seed)
    n = min(300, h * w)
    return {
        "sorted": np.sort(rng.choice(h * w, n, replace=False)),
        "unsorted": rng.choice(h * w, n, replace=False),
        "empty": np.array([], dtype=np.int64),
        "single": np.array([0]),
    }


def _maxdiff(a, b):
    """max|a-b|, defined as 0.0 for empty arrays."""
    if a.size == 0:
        return 0.0
    return float(np.max(np.abs(a - b)))


def _seq(fast_split, seed, bg_ratio=4.0, max_pts=65536):
    """BinSequence without __init__ (which would import TensorFlow)."""
    seq = object.__new__(BinSequence)
    seq.rng = np.random.default_rng(seed)
    seq.bg_ratio = bg_ratio
    seq.max_pts = max_pts
    seq.fast_split = fast_split
    seq.split_2d = split_2d_fast if fast_split else split_2d
    return seq


class TestSplitRowsParity(unittest.TestCase):
    def test_parity_vs_loop_for_every_idx_shape(self):
        """X and Norm (pre-division) match split_2d(...)[idx] exactly."""
        for shape in SHAPES:
            S = _spectrum(shape)
            X_ref, N_ref = split_2d(S.astype(np.float64), CROSS)
            for name, idx in _idx_variants(*shape).items():
                with self.subTest(shape=shape, idx=name):
                    X, N = split_2d_rows(S, idx, CROSS)
                    self.assertEqual(X.shape, (len(idx), 128, 1))
                    self.assertEqual(N.shape, (len(idx),))
                    self.assertEqual(_maxdiff(X, X_ref[idx]), 0.0)
                    self.assertEqual(_maxdiff(N, N_ref[idx]), 0.0)

    def test_norm_is_pre_division(self):
        """Norm must be the row norm BEFORE normalising, not 1.0.

        split_2d computes Norm on the un-normalised rows; returning the
        post-division norm would silently make every value 1.0.
        """
        S = _spectrum((256, 2048))
        idx = np.arange(0, 256 * 2048, 97)
        _, N = split_2d_rows(S, idx, CROSS)
        self.assertGreater(float(N.max()), 1.0)
        self.assertGreater(float(N.min()), 0.0)
        _, N_ref = split_2d(S.astype(np.float64), CROSS)
        self.assertEqual(float(np.max(np.abs(N - N_ref[idx]))), 0.0)

    def test_flat_rows_give_zero_norm_and_nan(self):
        """All-zero rows -> Norm 0 and NaN in X, as in split_2d."""
        S = np.zeros((64, 65), dtype=np.float32)
        X, N = split_2d_rows(S, np.array([0, 7]), CROSS)
        self.assertTrue(np.all(N == 0.0))
        self.assertTrue(np.all(np.isnan(X)))

    def test_accepts_list_index(self):
        """idx as a plain list must work (it is asarray-ed)."""
        S = _spectrum((64, 65))
        X, _ = split_2d_rows(S, [0, 3, 7], CROSS)
        self.assertEqual(X.shape, (3, 128, 1))

    def test_out_of_range_raises(self):
        S = _spectrum((64, 65))
        with self.assertRaises(IndexError):
            split_2d_rows(S, np.array([64 * 65]), CROSS)

    def test_full_range_matches_fast(self):
        """idx = arange(H*W) is the same as the full vectorised split."""
        for shape in SHAPES:
            S = _spectrum(shape)
            X_fast, N_fast = split_2d_fast(S.astype(np.float64), CROSS)
            X, N = split_2d_rows(S, np.arange(shape[0] * shape[1]), CROSS)
            with self.subTest(shape=shape):
                self.assertTrue(np.array_equal(X, X_fast))
                self.assertTrue(np.array_equal(N, N_fast))

    def test_not_slower_than_full_split(self):
        """Computing ~2900 rows must beat building the whole matrix."""
        S = _spectrum((256, 2048))
        idx = np.random.default_rng(2).choice(256 * 2048, 2900, replace=False)
        split_2d_rows(S, idx, CROSS)  # warm-up
        t0 = time.time()
        split_2d_fast(S.astype(np.float64), CROSS)
        t_full = time.time() - t0
        t0 = time.time()
        split_2d_rows(S, idx, CROSS)
        t_rows = time.time() - t0
        print(f"\nfull {t_full * 1e3:.1f} ms rows {t_rows * 1e3:.1f} ms "
              f"speedup {t_full / t_rows:.1f}x")
        self.assertLess(t_rows, t_full)


class TestPlanPoolIdx(unittest.TestCase):
    """plan_pool_idx must select exactly what build_pool used to select."""

    def _fake(self, h=64, w=64, n_pos=10, seed=0):
        rng = np.random.default_rng(seed)
        L = np.zeros((h, w), dtype=np.float32)
        L.reshape(-1)[rng.choice(h * w, size=n_pos, replace=False)] = 1.0
        X = rng.standard_normal((h * w, 128, 1)).astype(np.float32)
        return X, L

    def test_matches_build_pool_rows(self):
        X, L = self._fake()
        for max_pts in [None, 1 << 20, 14]:
            with self.subTest(max_pts=max_pts):
                idx, n_pos = plan_pool_idx(L, 10.0, max_pts,
                                           np.random.default_rng(0))
                px, py, n_pos_ref = build_pool(X, L, 10.0, max_pts,
                                               np.random.default_rng(0))
                self.assertEqual(n_pos, n_pos_ref)
                self.assertEqual(len(idx), len(px))
                self.assertTrue(np.array_equal(X[idx], px))
                self.assertTrue(np.array_equal(L.reshape(-1, 1)[idx], py))

    def test_positives_come_first(self):
        _, L = self._fake()
        idx, n_pos = plan_pool_idx(L, 10.0, None, np.random.default_rng(0))
        self.assertEqual(int(n_pos), int(L.sum()))
        self.assertTrue(np.all(L.reshape(-1)[idx[:n_pos]] > 0.5))
        self.assertTrue(np.all(L.reshape(-1)[idx[n_pos:]] < 0.5))


class TestPointsPath(unittest.TestCase):
    """BinSequence._points: fast rows path == full-split path."""

    def test_same_sample_as_full_split(self):
        rng = np.random.default_rng(3)
        S = rng.standard_normal((256, 512)).astype(np.float32)
        L = np.zeros((256, 512), dtype=np.float32)
        L.reshape(-1)[rng.choice(L.size, size=40, replace=False)] = 1.0
        for bg_ratio in [2.0, 4.0]:
            with self.subTest(bg_ratio=bg_ratio):
                fast = _seq(True, 11, bg_ratio=bg_ratio)
                slow = _seq(False, 11, bg_ratio=bg_ratio)
                Xf, yf = fast._points(S, L)
                Xs, ys = slow._points(S, L)
                self.assertTrue(np.array_equal(Xf, Xs))
                self.assertTrue(np.array_equal(yf, ys))
                self.assertEqual(Xf.dtype, np.float32)

    def test_rng_consumption_unchanged(self):
        """The reordering must not change how many rng draws are made."""
        rng = np.random.default_rng(5)
        S = rng.standard_normal((64, 64)).astype(np.float32)
        L = np.zeros((64, 64), dtype=np.float32)
        L.reshape(-1)[rng.choice(L.size, size=8, replace=False)] = 1.0
        a, b = _seq(True, 7), _seq(False, 7)
        a._points(S, L)
        b._points(S, L)
        self.assertEqual(a.rng.integers(1 << 30), b.rng.integers(1 << 30))


class TestPreextractRegression(unittest.TestCase):
    """End-to-end: the new pipeline must reproduce a saved pool byte-exactly.

    Requires the local 2.5 GB dataset and a pool built by the previous
    full-matrix implementation, so it is skipped elsewhere.
    """

    @unittest.skipUnless(
        os.path.isdir(os.path.join(DATASET_DIR, "spectra"))
        and os.path.isfile(os.path.join(POOL_DIR, "manifest.json")),
        "needs the local dataset and data/pre_elong pool")
    def test_first_spectra_are_byte_identical(self):
        man = json.load(open(os.path.join(POOL_DIR, "manifest.json")))
        ids = list(dict.fromkeys(man["train"] + man["val"]))[:3]
        self.assertTrue(ids, "pool manifest lists no spectra")
        # El pool en disco manda: si se generó con el minado del anillo
        # (--hard-frac > 0) hay que reproducir ESA selección y no la uniforme
        # histórica. Con `hard_frac` ausente o 0 el camino es el de siempre.
        hard = {}
        if man.get("hard_frac"):
            hard = {"hard_frac": float(man["hard_frac"]),
                    "hard_px": int(man["hard_px"])}
        # same seed and same order as the original preextract run
        rng = np.random.default_rng(man["seed"])
        for sid in ids:
            with self.subTest(sid=sid):
                S, L = load_pair(DATASET_DIR, sid)
                idx, n_pos = plan_pool_idx(L, man["pool_k"], man["max_pts"],
                                           rng, **hard)
                X, _ = split_2d_rows(S, idx, CROSS)
                X = np.asarray(X, dtype=np.float32)
                X[~np.isfinite(X)] = 0.0
                y = np.ascontiguousarray(L.reshape(-1, 1)[idx], dtype=np.float32)
                with np.load(os.path.join(POOL_DIR, f"{sid}.npz")) as z:
                    self.assertEqual(X.shape, (int(z["X"].shape[0]), 128, 1))
                    self.assertTrue(np.array_equal(X, z["X"]), sid)
                    self.assertTrue(np.array_equal(y, z["y"]), sid)
                    self.assertEqual(n_pos, int(z["n_pos"]), sid)
                    self.assertEqual(S.shape, SHAPE)
                    if "d" in z.files:
                        # El pool guarda la distancia al pico de cada fila de
                        # fondo: es lo que permite minar el anillo por época
                        # sin regenerarlo. Se fija también para que un cambio
                        # silencioso en el trazado del anillo no pase.
                        d_bg = distance_to_positive(L).reshape(-1)[idx[n_pos:]]
                        self.assertTrue(np.array_equal(d_bg.astype(np.uint8), z["d"]),
                                        sid)
                        self.assertEqual(int(z["hard_px"]), hard.get("hard_px", 0))


if __name__ == "__main__":
    unittest.main()
